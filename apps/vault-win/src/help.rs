/// Рисует окно справки. `open` — состояние окна, F1 переключает его снаружи.
pub fn show(ctx: &egui::Context, open: &mut bool) {
    if !*open {
        return;
    }

    let mut visible = true;
    egui::Window::new("Справка — Хранитель")
        .open(&mut visible)
        .collapsible(false)
        .resizable(true)
        .default_width(660.0)
        .default_height(560.0)
        .anchor(egui::Align2::CENTER_CENTER, egui::vec2(0.0, 0.0))
        .show(ctx, |ui| {
            ui.label(
                egui::RichText::new(
                    "Инструкция по всем функциям. Закрыть — F1, Ctrl+H, Esc или крестик.",
                )
                .weak()
                .small(),
            );
            ui.separator();

            egui::ScrollArea::vertical()
                .id_salt("help_scroll")
                .auto_shrink([false, false])
                .max_height(460.0)
                .show(ui, |ui| {
                    for (index, section) in SECTIONS.iter().enumerate() {
                        if index > 0 {
                            ui.add_space(6.0);
                        }
                        ui.label(egui::RichText::new(section.title).strong().size(16.0));
                        for line in section.body {
                            if let Some(item) = line.strip_prefix("- ") {
                                ui.horizontal_wrapped(|ui| {
                                    ui.spacing_mut().item_spacing.x = 6.0;
                                    ui.label("•");
                                    ui.label(item);
                                });
                            } else if line.is_empty() {
                                ui.add_space(4.0);
                            } else {
                                ui.label(*line);
                            }
                        }
                    }
                });
        });

    if !visible || ctx.input(|input| input.key_pressed(egui::Key::Escape)) {
        *open = false;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sections_are_filled() {
        assert!(SECTIONS.len() >= 10, "справка должна покрывать все функции");
        for section in SECTIONS {
            assert!(!section.title.is_empty());
            assert!(
                !section.body.is_empty(),
                "пустой раздел справки: {}",
                section.title
            );
        }
    }

    #[test]
    fn f1_event_is_visible_in_input() {
        let ctx = egui::Context::default();
        let mut raw = egui::RawInput::default();
        raw.events.push(egui::Event::Key {
            key: egui::Key::F1,
            physical_key: Some(egui::Key::F1),
            pressed: true,
            repeat: false,
            modifiers: egui::Modifiers::NONE,
        });
        let mut seen = false;
        let mut output = ctx.run_ui(raw, |ui| {
            seen = ui.ctx().input(|input| {
                input.events.iter().any(|event| {
                    matches!(
                        event,
                        egui::Event::Key {
                            key: egui::Key::F1,
                            pressed: true,
                            repeat: false,
                            ..
                        }
                    )
                })
            });
        });
        output.textures_delta.clear();
        assert!(seen, "F1 должно быть видно в событиях кадра");
    }

    #[test]
    fn help_window_renders_without_panic() {
        let ctx = egui::Context::default();
        let mut open = true;
        let mut output = ctx.run_ui(egui::RawInput::default(), |ui| show(ui.ctx(), &mut open));
        // В headless-прогоне рендерера нет: дельты текстур нужно очистить,
        // иначе epaint срабатывает на debug_assert при уничтожении.
        output.textures_delta.clear();
        assert!(open, "без запроса закрытия окно остаётся открытым");
    }
}
